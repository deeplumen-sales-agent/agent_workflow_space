#!/usr/bin/env python3
"""Generate thin platform adapters from the shared workflow source."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- GENERATED FILE: edit core/, workflows/, or memory/ instead. -->"

BODY = f"""{MARKER}
# Shared agent workflow

This file is generated from `agent_workflow_space`. Do not edit this file directly.

Before starting work:

1. Read `core/working-principles.md`.
2. Read `core/evidence-status.md` when reporting facts or completion status.
3. Read the workflow under `workflows/` that matches the current task.
4. Read relevant confirmed context under `memory/`.
5. Put new long-term information in `inbox/` as a candidate; do not overwrite formal memory automatically.

Keep facts, proposals, completed actions, blocked items, pending confirmation, and unverified inferences separate. Do not invent unknown values. Follow the current user instruction, platform safety constraints, and project rules before this shared guidance.
"""

CURSOR_BODY = f"""---
description: Shared rules and workflows for this repository
alwaysApply: true
---

{BODY}
"""


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"generated {path.relative_to(ROOT)}")


def main() -> None:
    write(ROOT / "AGENTS.md", BODY)
    write(ROOT / "CLAUDE.md", BODY)
    write(ROOT / "GEMINI.md", BODY)
    write(ROOT / ".cursor" / "rules" / "00-shared-agent-workflow.mdc", CURSOR_BODY)


if __name__ == "__main__":
    main()
